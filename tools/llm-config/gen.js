#!/usr/bin/env node
/**
 * Writes src/config/llmLocal.generated.ts (gitignored) from .env.llm.local
 * (gitignored). Test builds only: the keys end up in the JS bundle, readable
 * by anyone who has the app binary (docs/DECISIONS.md). Without the env file
 * the keys are empty and the app runs rules-only.
 * Variables: OPENAI_API_KEY, OPENAI_BASE_URL, CLAUDE_API_KEY (exactly this
 * name for the Anthropic key).
 * Never prints a key; only whether one was found.
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..', '..');
const envPath = path.join(root, '.env.llm.local');
const outPath = path.join(root, 'src', 'config', 'llmLocal.generated.ts');

/** KEY=value lines; # comments and blank lines ignored; optional quotes. */
function parseEnv(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
    if (m && !line.trimStart().startsWith('#')) {
      out[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
    }
  }
  return out;
}

const env = fs.existsSync(envPath)
  ? parseEnv(fs.readFileSync(envPath, 'utf8'))
  : {};
// LLM_CONFIG_NO_KEY=1: write empty keys (e.g. to build a check bundle).
const noKey = process.env.LLM_CONFIG_NO_KEY === '1';
function keyOf(name) {
  const k = noKey ? '' : env[name] ?? '';
  if (!/^[A-Za-z0-9_-]*$/.test(k)) {
    process.stderr.write(
      `llm-config: ${name} has unexpected characters; not written\n`,
    );
    process.exit(1);
  }
  return k;
}
const key = keyOf('OPENAI_API_KEY');
const anthropicKey = keyOf('CLAUDE_API_KEY');

const baseUrl = env.OPENAI_BASE_URL ?? '';
let host = '(default)';
if (baseUrl) {
  try {
    const u = new URL(baseUrl);
    if (u.protocol !== 'https:' || /['\\\s]/.test(baseUrl)) {
      throw new Error('bad');
    }
    host = u.host;
  } catch {
    process.stderr.write(
      'llm-config: OPENAI_BASE_URL must be an https URL; not written\n',
    );
    process.exit(1);
  }
}

// The host allowlist is enforced at runtime (src/config/llm.ts).
const body = `// Generated by tools/llm-config/gen.js from .env.llm.local. Gitignored: never commit.
export const LLM_LOCAL: {
  openaiApiKey: string;
  openaiBaseUrl: string;
  anthropicApiKey: string;
} = {
  openaiApiKey: '${key}',
  openaiBaseUrl: '${baseUrl}',
  anthropicApiKey: '${anthropicKey}',
};
`;
fs.mkdirSync(path.dirname(outPath), { recursive: true });
const previous = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
if (previous !== body) {
  fs.writeFileSync(outPath, body, { mode: 0o600 });
}
process.stdout.write(
  `llm-config: openai ${key ? 'key found' : 'no key'}; base URL host: ${host}; anthropic ${
    anthropicKey ? 'key found' : 'no key'
  }\n`,
);
