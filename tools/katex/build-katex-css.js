#!/usr/bin/env node
/**
 * Generates src/lesson/math/katexCss.generated.ts: KaTeX CSS with a subset of
 * its fonts inlined as base64 woff2, so the WebView math renderer works offline
 * without native asset folders.
 *
 * Only the font families needed for bac notation are kept; other @font-face
 * rules are dropped (KaTeX falls back to the system font for those glyphs).
 *
 * Run: npm run build:katex-css
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const KEEP_FONTS = new Set([
  'KaTeX_AMS-Regular',
  'KaTeX_Main-Regular',
  'KaTeX_Main-Italic',
  'KaTeX_Math-Italic',
  'KaTeX_Size1-Regular',
  'KaTeX_Size2-Regular',
  'KaTeX_Size3-Regular',
  'KaTeX_Size4-Regular',
]);

const root = path.resolve(__dirname, '../..');
const katexDist = path.join(root, 'node_modules/katex/dist');
const out = path.join(root, 'src/lesson/math/katexCss.generated.ts');
const version = require(path.join(
  root,
  'node_modules/katex/package.json',
)).version;

const css = fs.readFileSync(path.join(katexDist, 'katex.min.css'), 'utf8');

let kept = 0;
const result = css.replace(/@font-face\{[^}]*\}/g, rule => {
  const m = rule.match(/url\(fonts\/([\w-]+)\.woff2\)/);
  if (!m || !KEEP_FONTS.has(m[1])) {
    return '';
  }
  kept += 1;
  const b64 = fs
    .readFileSync(path.join(katexDist, 'fonts', `${m[1]}.woff2`))
    .toString('base64');
  return rule.replace(
    /src:[^}]*/,
    `src:url(data:font/woff2;base64,${b64}) format("woff2")`,
  );
});

if (kept !== KEEP_FONTS.size) {
  throw new Error(`Expected ${KEEP_FONTS.size} fonts, inlined ${kept}`);
}

fs.writeFileSync(
  out,
  `// GENERATED by tools/katex/build-katex-css.js from katex@${version}. Do not edit.\n` +
    `export const KATEX_CSS = ${JSON.stringify(result)};\n`,
);
console.log(
  `Wrote ${path.relative(root, out)} (${Math.round(
    result.length / 1024,
  )} KB, ${kept} fonts)`,
);
